const state = {
  lang: localStorage.getItem("aizhigit-lang") || "ru",
};

const getValue = (path, dictionary) =>
  path.split(".").reduce((acc, key) => (acc ? acc[key] : undefined), dictionary);

function setLanguage(lang) {
  state.lang = lang;
  localStorage.setItem("aizhigit-lang", lang);
  document.documentElement.lang = lang;
  const dictionary = translations[lang];

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = getValue(node.dataset.i18n, dictionary);
    if (typeof value === "string") node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const value = getValue(node.dataset.i18nPlaceholder, dictionary);
    if (typeof value === "string") node.placeholder = value;
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === lang);
  });

  renderDynamicContent(dictionary);
}

function renderDynamicContent(dictionary) {
  const featureGrid = document.querySelector("[data-feature-grid]");
  featureGrid.innerHTML = dictionary.features
    .map(
      (item) => `
        <article class="feature-card reveal">
          <span class="icon-box">${icons[item.icon]}</span>
          <h3>${item.title}</h3>
          <p>${item.text}</p>
        </article>
      `,
    )
    .join("");

  const routineList = document.querySelector("[data-routine-list]");
  routineList.innerHTML = dictionary.routines
    .map(
      (item) => `
        <article class="timeline-item reveal">
          <strong class="timeline-time">${item.time}</strong>
          <div>
            <h3>${item.title}</h3>
            <p>${item.text}</p>
          </div>
        </article>
      `,
    )
    .join("");

  const specList = document.querySelector("[data-spec-list]");
  specList.innerHTML = dictionary.specsList
    .map(
      (item) => `
        <article class="spec-item reveal">
          <span class="spec-value">${item.value}</span>
          <h3>${item.title}</h3>
          <p>${item.text}</p>
        </article>
      `,
    )
    .join("");



  const faqList = document.querySelector("[data-faq-list]");
  faqList.innerHTML = dictionary.faqs
    .map(
      (item, index) => `
        <article class="faq-item reveal ${index === 0 ? "is-open" : ""}">
          <button class="faq-question" type="button" aria-expanded="${index === 0 ? "true" : "false"}">
            ${item.question}
          </button>
          <div class="faq-answer">${item.answer}</div>
        </article>
      `,
    )
    .join("");

  bindFaq();
  observeReveals();
}

function bindFaq() {
  document.querySelectorAll(".faq-question").forEach((button) => {
    button.addEventListener("click", () => {
      const item = button.closest(".faq-item");
      const isOpen = item.classList.toggle("is-open");
      button.setAttribute("aria-expanded", String(isOpen));
    });
  });
}

let observer;
function observeReveals() {
  if (observer) observer.disconnect();
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reduceMotion) {
    document.querySelectorAll(".reveal").forEach((node) => node.classList.add("is-visible"));
    return;
  }

  observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.16 },
  );

  document.querySelectorAll(".reveal").forEach((node) => observer.observe(node));
}

